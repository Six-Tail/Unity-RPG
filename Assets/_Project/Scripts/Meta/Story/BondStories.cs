        /// <summary>캐릭터 id 의 개인 스토리 episode 화(1 ~ 3). 없으면 null.</summary>
        public static StoryScript Bond(string charId, int episode)
        {
            if (string.IsNullOrEmpty(charId)) return null;
            _bond ??= BuildBond();
            return _bond.TryGetValue($"bond_{charId}_{episode}", out var s) ? s : null;
        }

        private static Writer Ep(Cast who, int ep, string title, string bg) =>
            new Writer($"bond_{who.portrait.Substring("Characters/".Length)}_{ep}", $"{ep}화 {title}")
                .Bg(bg)
                .Title($"{who.name} 개인 스토리 {ep}화", title);

        private static Dictionary<string, StoryScript> BuildBond()
        {
            var d = new Dictionary<string, StoryScript>();
            void Add(Writer w) => d[w.script.id] = w.script;
            AddBondHigh(Add);
            AddBondLow(Add);
            return d;
        }

