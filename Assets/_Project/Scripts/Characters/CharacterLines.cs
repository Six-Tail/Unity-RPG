            _ => new[] { "길을 열어 줄게.", "출격 준비는 끝났어. 지휘관, 명령을." },
        };

        /// <summary>이 캐릭터의 로비 대사 후보(전용 대사 + 6성 대표 대사).</summary>
        public static List<string> Of(CharacterData c)
        {
            var list = new List<string>();
            if (c == null) return list;
            if (!string.IsNullOrEmpty(c.id) && Lines.TryGetValue(c.id, out var own)) list.AddRange(own);
            else list.AddRange(RoleLines(c.role));
            if (!string.IsNullOrEmpty(c.signatureLine) && !list.Contains(c.signatureLine)) list.Add(c.signatureLine);
            return list;
        }

        private static readonly Dictionary<string, int> _last = new();

        /// <summary>무작위 대사 1개(같은 캐릭터에서 바로 전 대사는 피함).</summary>
        public static string Random(CharacterData c)
        {
            var list = Of(c);
            if (list.Count == 0) return "";
            string key = c.id ?? c.name;
            _last.TryGetValue(key, out int prev);
            int i = UnityEngine.Random.Range(0, list.Count);
            if (list.Count > 1 && i == prev) i = (i + 1 + UnityEngine.Random.Range(0, list.Count - 1)) % list.Count;
            _last[key] = i;
            return list[i];
        }
    }
